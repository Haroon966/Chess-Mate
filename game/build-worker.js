// Bundles engine.js + bot.js + the worker body into worker-src.js so the bot can run in a Web Worker
// even when index.html is opened straight from disk (file://). Re-run after editing engine.js / bot.js:  node build-worker.js
const fs = require('fs');
const body = fs.readFileSync('engine.js', 'utf8') + '\n' + fs.readFileSync('bot.js', 'utf8') + '\n' +
  fs.readFileSync('bot-worker.js', 'utf8').replace(/^importScripts.*$/m, '');
fs.writeFileSync('worker-src.js', '// generated by build-worker.js — do not edit\nwindow.WORKER_SRC = ' + JSON.stringify(body) + ';\n');
console.log('worker-src.js', body.length, 'bytes');
