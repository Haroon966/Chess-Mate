#!/usr/bin/env node
/* Generates coach/data-embed.js: the coach JSON data inlined as globals so game.html / learn.html / coach.html work when opened
 * straight from disk (file://), where fetch() of local JSON is blocked.
 *   window.COACH_DATA = { coaches, lines, lessons }   window.COACH_AUDIO_MANIFEST = <coach/audio/manifest.json>
 * It also installs a tiny fetch shim for those 4 URLs (file:// always; http(s) only when the real fetch fails), so pages that
 * fetch them directly (pages.js) keep working without edits.
 *   node scripts/build-embed.js           write coach/data-embed.js
 *   node scripts/build-embed.js --check   exit 1 if coach/data-embed.js is missing or stale
 * scripts/build.js runs this automatically (writes with --out/--write-manifest, verifies with --check).
 * Re-run after editing coach/{coaches,lines,lessons}.json or coach/audio/manifest.json.
 */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const J = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));
const OUT = path.join(ROOT, 'coach', 'data-embed.js');

function generate() {
  const data = { coaches: J('coach/coaches.json'), lines: J('coach/lines.json'), lessons: J('coach/lessons.json') };
  let manifest = null;
  try { manifest = J('coach/audio/manifest.json'); } catch (e) { /* audio optional */ }
  return '// generated by scripts/build-embed.js - do not edit. Re-run: node scripts/build-embed.js\n' +
    '(function (w) {\n' +
    'w.COACH_DATA = ' + JSON.stringify(data) + ';\n' +
    (manifest ? 'w.COACH_AUDIO_MANIFEST = ' + JSON.stringify(manifest) + ';\n' : '') +
    `var URLS = [[/coach\\/coaches\\.json(?:[?#].*)?$/, function () { return w.COACH_DATA.coaches; }],
  [/coach\\/lines\\.json(?:[?#].*)?$/, function () { return w.COACH_DATA.lines; }],
  [/coach\\/lessons\\.json(?:[?#].*)?$/, function () { return w.COACH_DATA.lessons; }],
  [/coach\\/audio\\/manifest\\.json(?:[?#].*)?$/, function () { return w.COACH_AUDIO_MANIFEST; }]];
var realFetch = w.fetch;
if (typeof realFetch === 'function' && typeof Response === 'function') {
  w.fetch = function (input) {
    var u = String((input && input.url) || input), hit = null;
    for (var i = 0; i < URLS.length; i++) if (URLS[i][0].test(u)) { hit = URLS[i][1]; break; }
    var args = arguments, self = this;
    var fake = function () { var d = hit(); return d == null ? realFetch.apply(self, args) : Promise.resolve(new Response(JSON.stringify(d), { status: 200, headers: { 'Content-Type': 'application/json' } })); };
    if (!hit) return realFetch.apply(this, args);
    if (w.location && w.location.protocol === 'file:') return fake();
    return realFetch.apply(this, args).then(function (r) { return r && r.ok ? r : fake(); }, fake);
  };
}
})(window);
`;
}
module.exports = { generate, OUT };
if (require.main === module) {
  const text = generate();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
    if (cur !== text) { console.error('coach/data-embed.js is ' + (cur == null ? 'missing' : 'stale') + ' - run: node scripts/build-embed.js'); process.exit(1); }
    console.log('coach/data-embed.js is up to date');
  } else { fs.writeFileSync(OUT, text); console.log('wrote coach/data-embed.js (' + text.length + ' bytes)'); }
}
