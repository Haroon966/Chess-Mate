#!/usr/bin/env node
/* Chess Mate build/check tool (plain node, no deps).
 *   node scripts/build.js --check                 validate + size report, writes nothing
 *   node scripts/build.js --write-manifest        also write precache-manifest.json into the source tree (local dev/testing)
 *   node scripts/build.js --out dist [--no-audio] copy a clean deployable tree to dist/, stamp sw.js CACHE_VERSION,
 *                                                 write precache-manifest.json there.  --no-audio skips coach/audio/**.mp3 (testing only)
 *                                                 --force writes output even when validation fails (testing only)
 * coach/data-embed.js (file:// fallback data, see scripts/build-embed.js) is regenerated by --out/--write-manifest and verified by --check.
 * Exit code 1 if any validation error is found.
 * NOTE: lives in scripts/ (not tools/) because the repo root .gitignore ignores every directory named tools/.
 */
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const optVal = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : null; };
const OUT = optVal('--out');
const CHECK_ONLY = flag('--check') || (!OUT && !flag('--write-manifest'));
const NO_AUDIO = flag('--no-audio');

// ---- what is NOT shipped to the deployed site ----
const EXCLUDE_DIRS = ['tools', 'scripts', 'node_modules', 'dist', '_site', '.git', '.github', 'tests', 'lessonhunt'];
const EXCLUDE_FILES = [/\.md$/i, /^SPEC\.md$/, /^test_.*\.js$/, /^validate_.*\.js$/, /^build-worker\.js$/, /^lessonhunt/i,
  /^\.gitignore$/, /^\.DS_Store$/, /\.log$/, /\.map$/, /~$/, /^precache-manifest\.json$/];
// ---- what is precached (app shell). mp3 audio, 404.html, sw.js are deliberately not ----
const PRECACHE_EXT = new Set(['.html', '.js', '.css', '.png', '.jpg', '.svg', '.ico', '.webmanifest', '.json', '.woff2', '.woff', '.ttf', '.webp']);
const PRECACHE_SKIP = [/^sw\.js$/, /^404\.html$/, /^\.nojekyll$/, /^coach\/audio\/(?!manifest\.json$)/];

const errors = [], warns = [];
const err = (m) => errors.push(m), warn = (m) => warns.push(m);
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) { if (!EXCLUDE_DIRS.some((d) => e.name === d || (d === 'lessonhunt' && e.name.startsWith(d)))) walk(full, out); }
    else if (e.isFile() && !EXCLUDE_FILES.some((re) => re.test(e.name))) out.push(full);
  }
  return out;
}
// coach/data-embed.js (file:// fallback data) must match coach/*.json: regenerate when writing, otherwise just verify
{
  const emb = require('./build-embed.js'), text = emb.generate();
  const cur = fs.existsSync(emb.OUT) ? fs.readFileSync(emb.OUT, 'utf8') : null;
  if (cur !== text) {
    if (OUT || flag('--write-manifest')) { fs.writeFileSync(emb.OUT, text); console.log('regenerated coach/data-embed.js'); }
    else err('coach/data-embed.js is ' + (cur == null ? 'missing' : 'stale') + ' - run: node scripts/build-embed.js');
  }
}
let files = walk(ROOT).map(rel).sort();
if (NO_AUDIO) files = files.filter((f) => !/^coach\/audio\/.+\.mp3$/.test(f));
const size = (f) => fs.statSync(path.join(ROOT, f)).size;
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');

// ---- validations ----
const ROOT_ABS = {
  html: [/\b(?:src|href|action|poster|data)\s*=\s*["']\/(?!\/)/i, /\bcontent\s*=\s*["']\d+;\s*url=\//i],
  css: [/url\(\s*["']?\/(?!\/)/i, /@import\s+["']\/(?!\/)/i],
  js: [/\b(?:fetch|importScripts|register|Worker|SharedWorker|open|Request)\s*\(\s*["'`]\/(?!\/)/, /\.(?:src|href)\s*=\s*["'`]\/(?!\/)/, /new URL\(\s*["'`]\/(?!\/)/],
  webmanifest: [/"(?:src|start_url|scope|id|url)"\s*:\s*"\/(?!\/)/],
};
const kind = (f) => ({ '.html': 'html', '.css': 'css', '.js': 'js', '.webmanifest': 'webmanifest' }[path.extname(f)]);
for (const f of files) {
  const k = kind(f); if (!k) continue;
  const text = read(f);
  text.split('\n').forEach((line, i) => { for (const re of ROOT_ABS[k]) if (re.test(line)) err(`root-absolute URL in ${f}:${i + 1}: ${line.trim().slice(0, 120)}`); });
}

// every local reference from html / css resolves to a shipped file
const shipped = new Set(files);
const skipRef = /^(?:[a-z][a-z0-9+.-]*:|\/\/|#|data:|mailto:|javascript:)/i;
function checkRef(from, ref) {
  ref = ref.trim(); if (!ref || skipRef.test(ref)) return;
  const clean = ref.split(/[?#]/)[0]; if (!clean) return;
  const target = path.posix.normalize(path.posix.join(path.posix.dirname(from), clean));
  if (clean.endsWith('/')) return;
  if (!shipped.has(target)) err(`${from} references missing file: ${ref}`);
}
for (const f of files.filter((x) => x.endsWith('.html'))) {
  const t = read(f);
  for (const m of t.matchAll(/\b(?:src|href|poster)\s*=\s*["']([^"']+)["']/gi)) {
    checkRef(f, m[1]);
  }
}
for (const f of files.filter((x) => x.endsWith('.css'))) for (const m of read(f).matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)/gi)) checkRef(f, m[1]);

// manifest + icons
function pngSize(p) { const b = fs.readFileSync(p); return b.toString('ascii', 1, 4) === 'PNG' ? [b.readUInt32BE(16), b.readUInt32BE(20)] : null; }
try {
  const mf = JSON.parse(read('manifest.webmanifest'));
  for (const k of ['name', 'short_name', 'start_url', 'scope', 'display', 'theme_color', 'background_color', 'icons']) if (!mf[k]) err(`manifest missing ${k}`);
  const purposes = new Set();
  for (const ic of mf.icons || []) {
    const p = path.join(ROOT, ic.src);
    if (!fs.existsSync(p)) { err(`manifest icon missing: ${ic.src}`); continue; }
    (ic.purpose || 'any').split(' ').forEach((x) => purposes.add(x + ':' + ic.sizes));
    if (ic.type === 'image/png') {
      const s = pngSize(p), want = ic.sizes.split('x').map(Number);
      if (!s || s[0] !== want[0] || s[1] !== want[1]) err(`icon ${ic.src} is ${s} but manifest says ${ic.sizes}`);
    }
  }
  for (const need of ['any:192x192', 'any:512x512', 'maskable:512x512']) if (!purposes.has(need)) err(`manifest lacks icon ${need}`);
  for (const s of mf.shortcuts || []) checkRef('manifest.webmanifest', s.url);
  checkRef('manifest.webmanifest', mf.start_url);
  if (!/^\.\//.test(mf.start_url) || !/^\.\/?$/.test(mf.scope)) err('manifest start_url/scope must be relative (./...)');
} catch (e) { err('manifest.webmanifest: ' + e.message); }
{ const a = path.join(ROOT, 'icons/apple-touch-icon.png'); if (!fs.existsSync(a)) err('icons/apple-touch-icon.png missing'); else { const s = pngSize(a); if (!s || s[0] !== 180) err('apple-touch-icon must be 180x180'); } }

// every page carries the PWA head tags (see scripts/head-snippet.html). offline/404 are standalone and exempt.
const HEAD_REQUIRED = [['manifest link', /<link[^>]+rel=["']manifest["'][^>]+href=["']manifest\.webmanifest["']/i],
  ['theme-color', /<meta[^>]+name=["']theme-color["']/i], ['apple-mobile-web-app-capable', /<meta[^>]+name=["']apple-mobile-web-app-capable["']/i],
  ['apple-mobile-web-app-title', /<meta[^>]+name=["']apple-mobile-web-app-title["']/i], ['apple-mobile-web-app-status-bar-style', /<meta[^>]+name=["']apple-mobile-web-app-status-bar-style["']/i],
  ['apple-touch-icon', /<link[^>]+rel=["']apple-touch-icon["']/i], ['viewport-fit=cover', /viewport-fit=cover/i], ['pwa.js (defer)', /<script[^>]+src=["']pwa\.js["'][^>]*defer|<script[^>]+defer[^>]+src=["']pwa\.js["']/i]];
for (const f of files.filter((x) => /^[^/]+\.html$/.test(x) && !['offline.html', '404.html'].includes(x))) {
  const t = read(f); for (const [n, re] of HEAD_REQUIRED) if (!re.test(t)) err(`${f} is missing PWA head tag: ${n}`);
}
for (const need of ['index.html', 'offline.html', '404.html', 'sw.js', 'pwa.js', '.nojekyll']) if (!shipped.has(need)) err(`required file missing: ${need}`);

// ---- precache list + version ----
const precache = files.filter((f) => PRECACHE_EXT.has(path.extname(f)) && !PRECACHE_SKIP.some((re) => re.test(f)));
const h = crypto.createHash('sha1');
for (const f of precache) { h.update(f + '\0'); h.update(fs.readFileSync(path.join(ROOT, f))); }
h.update(fs.readFileSync(path.join(ROOT, 'sw.js')));
const VERSION = h.digest('hex').slice(0, 12);
const manifestJson = JSON.stringify({ version: VERSION, urls: precache }, null, 1) + '\n';

// ---- size report ----
const total = files.reduce((n, f) => n + size(f), 0);
const audio = files.filter((f) => f.endsWith('.mp3')).reduce((n, f) => n + size(f), 0);
const MB = (n) => (n / 1048576).toFixed(2) + ' MB';
const nonAudio = files.filter((f) => !f.endsWith('.mp3')).sort((a, b) => size(b) - size(a)).slice(0, 8);
console.log(`Chess Mate build ${VERSION}${NO_AUDIO ? ' (no audio)' : ''}`);
console.log(`  files: ${files.length}  total: ${MB(total)}  audio: ${MB(audio)} (${files.filter((f) => f.endsWith('.mp3')).length} clips)  precache: ${precache.length} files / ${MB(precache.reduce((n, f) => n + size(f), 0))}`);
console.log('  largest non-audio files:'); nonAudio.forEach((f) => console.log(`    ${MB(size(f)).padStart(10)}  ${f}`));
if (total > 1024 ** 3) warn(`site is ${MB(total)} (> 1 GB; GitHub Pages recommended limit)`);
for (const f of files) if (size(f) > 50 * 1048576) warn(`${f} is ${MB(size(f))} (> 50 MB)`);
for (const f of files) if (size(f) > 100 * 1048576) err(`${f} exceeds GitHub's 100 MB file limit`);

// ---- output ----
if (flag('--write-manifest')) { fs.writeFileSync(path.join(ROOT, 'precache-manifest.json'), manifestJson); console.log('  wrote precache-manifest.json (source tree)'); }
if (OUT && (!errors.length || flag('--force'))) {
  const dest = path.resolve(process.cwd(), OUT);
  if (dest === ROOT || ROOT.startsWith(dest + path.sep)) { console.error('refusing to use that --out'); process.exit(1); }
  fs.rmSync(dest, { recursive: true, force: true });
  for (const f of files) { const to = path.join(dest, f); fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(path.join(ROOT, f), to); }
  const swp = path.join(dest, 'sw.js'), sw = fs.readFileSync(swp, 'utf8');
  if (!sw.includes("'__BUILD__'")) err('sw.js has no __BUILD__ token');
  fs.writeFileSync(swp, sw.replace("'__BUILD__'", `'${VERSION}'`));
  fs.writeFileSync(path.join(dest, 'precache-manifest.json'), manifestJson);
  console.log(`  deployable tree written to ${dest}`);
} else if (OUT) console.log('  NOT writing output because of errors');

warns.forEach((w) => console.log('WARN  ' + w));
errors.forEach((e) => console.log('ERROR ' + e));
console.log(errors.length ? `FAILED: ${errors.length} error(s)` : 'OK: all checks passed');
process.exit(errors.length ? 1 : 0);
